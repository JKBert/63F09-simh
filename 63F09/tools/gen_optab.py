#!/usr/bin/env python3
"""gen_optab.py : generates 63F09/m63f09_optab.h from the opcode table of binutils-gdb.

  Copyright (C) 2026 Dr. BERTRAND Joël, Claude

The table (opcodes/m6809-opc.c) is the one the assembler and the disassembler use, verified against the VHDL and by the
torture tests as-new / A09 : the simulator decodes from it instead of keeping a second copy.  One row per (mnemonic,
addressing mode) ; the same (page, opcode) appears several times when the encoding depends on the CPU state (16 or 32
bits, 6809 / 6309 / 63F09, FPU), and the 'arch' mask says in which.

usage: gen_optab.py [binutils-gdb directory] [output file]
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/cvs/gcc/binutils-gdb')
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'm63f09_optab.h')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def read_defines(path):
    """Numeric #define of m6809.h, evaluated (the arch masks are expressions of other macros)."""
    text = strip_comments(open(path).read())
    text = re.sub(r'\\\n', ' ', text)
    raw = {}
    for m in re.finditer(r'^[ \t]*#[ \t]*define[ \t]+(\w+)[ \t]+(.+)$', text, flags=re.M):
        raw[m.group(1)] = m.group(2).strip()
    cache = {}

    def value(name):
        if name in cache:
            return cache[name]
        expr = raw[name]
        expr = re.sub(r'\b[A-Za-z_]\w*\b', lambda t: str(value(t.group(0))) if t.group(0) in raw else t.group(0), expr)
        cache[name] = eval(expr, {}, {})
        return cache[name]

    out = {}
    for name in raw:
        try:
            out[name] = value(name)
        except Exception:
            pass
    return out


def main():
    hdr = os.path.join(SRC, 'include/opcode/m6809.h')
    opc = os.path.join(SRC, 'opcodes/m6809-opc.c')
    defs = read_defines(hdr)
    arch_names = sorted(n for n in defs if n.startswith('M6809_OPCODE_'))
    addr_names = sorted((n for n in defs if n.startswith('ADDR_')), key=lambda n: defs[n])

    text = strip_comments(open(opc).read())
    pat = re.compile(r'M6809_INSN\s*\(\s*(\w+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(\d+)\s*,'
                     r'\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([^,]+?)\s*,\s*([^)]+?)\s*\)')
    rows = []
    for m in pat.finditer(text):
        name, opcode, page, length, c09, c63, cf09, arch, mode = m.groups()

        def ev(expr):
            expr = re.sub(r'\b[A-Za-z_]\w*\b', lambda t: str(defs[t.group(0)]), expr)
            return eval(expr, {}, {})

        rows.append((name, int(opcode, 0), int(page, 0), int(length), int(c09), int(c63), int(cf09), ev(arch), ev(mode)))
    n_insn = len(re.findall(r'M6809_INSN\s*\(', text))
    if n_insn != len(rows):
        sys.exit('gen_optab: %d M6809_INSN in the source, %d parsed' % (n_insn, len(rows)))

    rows.sort(key=lambda r: (r[2], r[1], r[7], r[8]))
    with open(OUT, 'w') as f:
        f.write('/* GENERATED by 63F09/tools/gen_optab.py from opcodes/m6809-opc.c and include/opcode/m6809.h : do not edit.\n')
        f.write('   Copyright (C) 2026 Dr. BERTRAND Joël, Claude\n')
        f.write('   %d rows, sorted by (page, opcode, arch, mode). */\n\n' % len(rows))
        f.write('#ifndef M63F09_OPTAB_H\n#define M63F09_OPTAB_H\n\n#include <stdint.h>\n\n')
        for n in arch_names:
            f.write('#define M63_%-34s 0x%04x\n' % (n[len('M6809_'):], defs[n]))
        f.write('\n')
        for n in addr_names:
            f.write('#define M63_%-20s 0x%08x\n' % (n, defs[n]))
        names = sorted(set(r[0] for r in rows))
        f.write('\n/* mnemonic identifiers (one per distinct name of the table, aliases such as asl/lsl are distinct) */\nenum {\n')
        for i, n in enumerate(names):
            f.write('    MN_%s%s\n' % (n.upper(), ',' if i + 1 < len(names) else ''))
        f.write('};\n#define M63_NMN %d\n' % len(names))
        f.write('\ntypedef struct {\n    const char *name;\n    uint16_t mn;        /* MN_* */\n    uint8_t opcode;\n    uint8_t page;       /* 0x00, 0x10, 0x11, 0x18, 0x1b */\n'
                '    uint8_t length;     /* bytes of the instruction in its CPU state */\n'
                '    uint8_t cycles_6809, cycles_6309, cycles_63f09;   /* minimum, 0 = unknown or not available */\n'
                '    uint16_t arch;      /* CPU states in which this row applies */\n    uint32_t mode;      /* M63_ADDR_* */\n} m63f09_op_t;\n\n')
        f.write('#define M63F09_NOPS %d\n\n' % len(rows))
        f.write('static const m63f09_op_t m63f09_optab[M63F09_NOPS] = {\n')
        for r in rows:
            f.write('    { "%s", MN_%s, 0x%02x, 0x%02x, %d, %d, %d, %d, 0x%04x, 0x%08x },\n' % ((r[0], r[0].upper()) + r[1:]))
        f.write('};\n\n#endif\n')
    pages = {}
    for r in rows:
        pages[r[2]] = pages.get(r[2], 0) + 1
    print('%d rows written to %s ; per page: %s' % (len(rows), os.path.normpath(OUT), ', '.join('$%02x=%d' % (p, pages[p]) for p in sorted(pages))))


main()
